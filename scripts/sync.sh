#!/usr/bin/env bash
# Copies prompt.md into every file that AI coding tools load automatically.
# Edit prompt.md only, then run: ./scripts/sync.sh
set -euo pipefail

cd "$(dirname "$0")/.."

SOURCE="prompt.md"
NOTICE="<!-- AUTO-GENERATED from prompt.md by scripts/sync.sh. Do not edit this file directly. -->"
DIRECTIVE="> **Mandatory system instruction:** Apply everything below to every response in this session, starting with your first reply. These rules override default agreeable or flattering behavior."

write_copy() {
  local target="$1" frontmatter="${2:-}"
  mkdir -p "$(dirname "$target")"
  {
    if [ -n "$frontmatter" ]; then printf '%s\n\n' "$frontmatter"; fi
    printf '%s\n\n%s\n\n' "$NOTICE" "$DIRECTIVE"
    cat "$SOURCE"
  } > "$target"
  echo "wrote $target"
}

# OpenCode, OpenAI Codex, Cursor, Zed, Jules, Aider (via config), and other AGENTS.md readers
write_copy "AGENTS.md"
# Claude Code
write_copy "CLAUDE.md"
# Gemini CLI
write_copy "GEMINI.md"
# GitHub Copilot
write_copy ".github/copilot-instructions.md"
# Cursor (always-on project rule)
write_copy ".cursor/rules/anti-sycophancy.mdc" $'---\ndescription: Ruthless reality-check and anti-sycophancy rules\nalwaysApply: true\n---'
# Windsurf (always-on rule)
write_copy ".windsurf/rules/anti-sycophancy.md" $'---\ntrigger: always_on\n---'
# Cline
write_copy ".clinerules/anti-sycophancy.md"
